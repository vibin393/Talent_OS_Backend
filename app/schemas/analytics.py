"""Predictive analytics API schemas (Epic 48). Decimals are strings (Phase 3: no floats).

Internal-only: none of these models is ever a Client / Vendor / Worker portal schema; the portal field guard
forbids ``prediction*``, ``attrition*``, ``drop_risk*`` and ``time_to_fill*`` on every portal principal.
"""

import uuid
from datetime import datetime
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field

ModelKind = Literal["time_to_fill", "offer_drop", "attrition"]
SubjectKind = Literal["demand", "offer", "placement"]
EntryStatus = Literal["ok", "insufficient_data", "disabled", "no_model"]
SUPPORTING_SIGNAL = "Supporting signal"
DISCLAIMER = "Supporting signal, not a decision. Generated by AI from the model's contributions; it never changes the score."


class Progress(BaseModel):
    n: int
    required: int
    n_minority: int | None = None
    required_minority: int | None = None


class Interval(BaseModel):
    p20: str
    p80: str


class ContributionOut(BaseModel):
    key: str
    label: str
    value_display: str
    contribution: str
    direction: Literal["up", "down"]
    display: str


class PredictionEntry(BaseModel):
    kind: ModelKind
    kind_label: str
    status: EntryStatus
    label: Literal["Supporting signal"] = SUPPORTING_SIGNAL
    prediction_id: uuid.UUID | None = None
    model_id: uuid.UUID | None = None
    model_version: int | None = None
    computed_at: datetime | None = None
    score: str | None = None
    predicted_days: str | None = None
    interval: Interval | None = None
    band: Literal["low", "medium", "high"] | None = None
    contributions: list[ContributionOut] = []
    explanation_status: Literal["none", "ok", "unavailable"] = "none"
    explanation_text: str | None = None
    progress: Progress | None = None


class PredictionsOut(BaseModel):
    subject_kind: SubjectKind
    subject_id: uuid.UUID
    predictions: list[PredictionEntry]


class BatchItem(BaseModel):
    subject_id: uuid.UUID
    kind: ModelKind
    status: EntryStatus
    band: Literal["low", "medium", "high"] | None = None
    score: str | None = None
    predicted_days: str | None = None
    interval: Interval | None = None


class BatchOut(BaseModel):
    items: list[BatchItem]


class ExplanationOut(BaseModel):
    status: Literal["ok", "unavailable"]
    text: str | None = None
    disclaimer: str = DISCLAIMER


class PredictionExplanation(BaseModel):
    """Model output schema of ``prediction_explanation`` (the gateway's ``emit_result`` tool)."""

    model_config = ConfigDict(extra="ignore")

    text: str = Field(min_length=1, max_length=400)
    cited_feature_keys: list[str] = []


# ---------------------------------------------------------------- model cards
class CalibrationBin(BaseModel):
    bin: int
    predicted: str
    observed: str
    n: int


class FeatureRank(BaseModel):
    key: str
    label: str
    sign: Literal["+", "-"]
    rank: int


class ModelDetail(BaseModel):
    id: uuid.UUID
    version: int
    trained_at: datetime | None
    n_samples: int
    n_minority: int | None
    metrics: dict[str, str]
    baseline: dict[str, str]
    calibration: list[CalibrationBin]
    features: list[FeatureRank]


class ModelRef(BaseModel):
    id: uuid.UUID
    version: int
    status: str
    trained_at: datetime | None
    failure_code: str | None


class HistoryRow(BaseModel):
    id: uuid.UUID
    version: int
    status: str
    trained_at: datetime | None
    n_samples: int
    failure_code: str | None


class ModelCard(BaseModel):
    kind: ModelKind
    kind_label: str
    enabled: bool
    status: Literal["active", "insufficient_data", "failed", "disabled", "no_model", "training"]
    reduced: bool
    active: ModelDetail | None = None
    latest: ModelRef | None = None
    progress: Progress | None = None
    excluded_features: list[str] = []
    history: list[HistoryRow] = []


class ModelCardsOut(BaseModel):
    cards: list[ModelCard]


class TrainQueuedOut(BaseModel):
    queued: bool


# ---------------------------------------------------------------- settings
class BandThreshold(BaseModel):
    medium: str
    high: str


class BandThresholds(BaseModel):
    offer_drop: BandThreshold
    attrition: BandThreshold


class EnabledKinds(BaseModel):
    time_to_fill: bool
    offer_drop: bool
    attrition: bool


class AnalyticsSettingsOut(BaseModel):
    enabled_kinds: EnabledKinds
    min_samples: int
    min_minority: int
    band_thresholds: BandThresholds
    history_months: int
    platform_min_samples: int
    platform_min_minority: int


class EnabledKindsIn(BaseModel):
    model_config = ConfigDict(extra="forbid")

    time_to_fill: bool | None = None
    offer_drop: bool | None = None
    attrition: bool | None = None


class AnalyticsSettingsIn(BaseModel):
    model_config = ConfigDict(extra="forbid")

    enabled_kinds: EnabledKindsIn | None = None
    min_samples: int | None = Field(default=None, le=100000)
    min_minority: int | None = Field(default=None, le=100000)
    band_thresholds: BandThresholds | None = None
    history_months: int | None = Field(default=None, ge=6, le=120)
