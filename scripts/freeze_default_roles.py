# ruff: noqa: E501
"""Epic 79 phase close: generate the Phase 5 merge revision (one-off generator, not a runtime dependency).

    ./venv/Scripts/python.exe scripts/freeze_default_roles.py <out.py> [--date YYYYMMDD]

Reads the Phase 5 branch heads from ``alembic/versions`` (via alembic's ScriptDirectory), the Phase 4 merge's
``ROLE_LABELS`` plus the new Integration Administrator, and regenerates ``FROZEN_DEFAULT_ROLES`` from
``app.core.permissions.DEFAULT_ROLES`` (Tenant Admin excluded). The Phase 4 merge body (``_UPDATE_SQL`` /
``_INSERT_SQL`` / ``_sync`` / ``upgrade`` / ``downgrade``) is copied verbatim; the ``depends_on`` effective-head tuple
is kept so ``alembic heads`` shows one head.
"""

import argparse
import importlib.util
import pprint
import sys
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(BACKEND))
P4_MERGE = BACKEND / "alembic" / "versions" / "20261009_900_merge_phase4.py"
INTEGRATION_ADMIN_LABEL = {
    "name": "Integration Administrator",
    "description": "Marketplace, Installations, webhooks, the ecosystem console and the Ecosystem Kill Switch; "
    "no business-data permissions.",
}


def p5_heads() -> list[str]:
    from alembic.config import Config
    from alembic.script import ScriptDirectory

    script = ScriptDirectory.from_config(Config(str(BACKEND / "alembic.ini")))
    return sorted(h for h in script.get_heads() if h.split("_")[1].startswith("5"))


def frozen() -> dict[str, dict[str, str]]:
    from app.core.permissions import DEFAULT_ROLES, TENANT_ADMIN

    return {
        r.key: {k: str(getattr(v, "value", v)) for k, v in sorted(r.permissions.items())}
        for r in sorted(DEFAULT_ROLES, key=lambda r: r.key)
        if r.key != TENANT_ADMIN
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("out")
    parser.add_argument("--date", default="20261010")
    args = parser.parse_args()
    spec = importlib.util.spec_from_file_location("p4merge", P4_MERGE)
    assert spec and spec.loader
    p4 = importlib.util.module_from_spec(spec)
    sys.modules["p4merge"] = p4
    spec.loader.exec_module(p4)
    labels = {**p4.ROLE_LABELS, "integration_administrator": INTEGRATION_ADMIN_LABEL}
    roles = frozen()
    missing = sorted(set(roles) - set(labels))
    assert not missing, f"no ROLE_LABELS for {missing}"
    heads = p5_heads()
    rev = f"{args.date}_900_merge_phase5"
    source = P4_MERGE.read_text(encoding="utf-8")
    body = source[source.index("_UPDATE_SQL = (") :]
    text = f'''# ruff: noqa: E501
"""Phase 5 close: merge every Phase 5 epic branch (Epics 66-79) into one head and re-sync the SYSTEM non-admin
default roles of every tenant with the Phase 5 ``DEFAULT_ROLES`` (the only Phase 5 default-role resync, build plan
§7, FR-412).

The role definitions are FROZEN here (generated by ``scripts/freeze_default_roles.py`` from ``app/core/permissions.py``
at Phase 5 close-out, including every ``_EPIC6x/7x_ROLE_GRANTS`` -- ``posting:publish_external`` (70), ``hrms:sync`` /
``ledger:sync`` (71), ``mcp:use`` (73), ``voice:call`` (76), ``campaign:copy_approve`` (78), ``integration:view`` (66)
-- and the new Integration Administrator system role). The migration never imports app code. Like
``20261009_900_merge_phase4`` it touches only ``is_system = true`` rows whose key is in the snapshot; custom roles and
the Tenant Admin are never modified. System roles missing from a tenant (``integration_administrator``) are inserted.
Downgrade is a no-op (data-only).

Revision ID: {rev}
Revises: {len(heads)} Phase 5 heads (+2 effective Phase 2 heads via depends_on)
Create Date: {args.date[:4]}-{args.date[4:6]}-{args.date[6:]}

"""

import json
from collections.abc import Sequence

import sqlalchemy as sa

from alembic import op

revision: str = "{rev}"
down_revision: str | tuple[str, ...] | None = {pprint.pformat(tuple(heads), width=110)}
branch_labels: str | Sequence[str] | None = None
# Effective heads (already merged into the Phase 2 / Phase 3 close through depends_on).
depends_on: str | Sequence[str] | None = ("20261003_201_03_external_auth", "20261005_216_04_billing_notes")

TENANT_ADMIN_KEY = "tenant_admin"

# role key -> {{"name", "description"}} for inserting system roles a tenant does not have yet.
ROLE_LABELS: dict[str, dict[str, str]] = {pprint.pformat(labels, width=110, sort_dicts=True)}

# role key -> {{permission: scope}} -- frozen snapshot of DEFAULT_ROLES at Phase 5 close (Tenant Admin excluded).
FROZEN_DEFAULT_ROLES: dict[str, dict[str, str]] = {pprint.pformat(roles, width=110, sort_dicts=True)}

{body}'''
    Path(args.out).write_text(text, encoding="utf-8")
    print(f"wrote {args.out}: {rev} <- {heads}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
