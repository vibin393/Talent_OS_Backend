_UPDATE_SQL = (
    "UPDATE roles AS r SET permissions = m.value, updated_at = now() "
    "FROM jsonb_each(CAST(:map AS jsonb)) AS m "
    "WHERE r.key = m.key AND r.is_system = true AND r.key <> :admin "
    "AND r.permissions IS DISTINCT FROM m.value"
)

_INSERT_SQL = (
    "INSERT INTO roles "
    "(id, tenant_id, key, name, description, is_system, permissions, created_at, updated_at) "
    "SELECT gen_random_uuid(), t.id, CAST(:key AS varchar), CAST(:name AS varchar), "
    "CAST(:description AS varchar), true, CAST(:perms AS jsonb), now(), now() "
    "FROM tenants t "
    "WHERE NOT EXISTS (SELECT 1 FROM roles r WHERE r.tenant_id = t.id AND r.key = CAST(:key AS varchar))"
)


def _sync(bind: sa.engine.Connection, tenant_filter: str, extra: dict[str, object]) -> None:
    params = {"map": json.dumps(FROZEN_DEFAULT_ROLES, sort_keys=True), "admin": TENANT_ADMIN_KEY, **extra}
    bind.execute(sa.text(_UPDATE_SQL + tenant_filter.replace("t.id", "r.tenant_id")), params)
    for key, perms in FROZEN_DEFAULT_ROLES.items():
        label = ROLE_LABELS[key]
        bind.execute(
            sa.text(_INSERT_SQL + tenant_filter),
            {
                "key": key,
                "name": label["name"],
                "description": label["description"],
                "perms": json.dumps(perms, sort_keys=True),
                **extra,
            },
        )


